"""
Xylarium crystals: the lattice a mind's transformations live on - coordinates and charts, never search.

The carrier is netstratum's (engine/solver-verify): hue grids (0..9), planar or stacked into volumes. Its
vocabulary is mirrored by op code, append-only wire law:

    1 Rotate90 · 2 Rotate180 · 3 Rotate270 · 4 FlipH · 5 FlipV · 6 Transpose · 7 Recolor(map[10])
    volumetric: PerLayer(op) · FlipStack · CycleLayers

Every word over that vocabulary is a point on a product lattice, and reduces to one normal form:

    stack element  in D_L   the dihedral group of an L-layer stack (generated by FlipStack, CycleLayers)
    frame element  in D4    the eight symmetries of the plane (generated by the frame ops)
    colour map     hue -> hue

Per-layer operators commute with stack operators, and a recolour commutes with every geometric operator, so a word
of any length IS its coordinate (stack, frame, colour): depth disappears into the point it names. That is the
coboundary reduction - frame distortion stripped in polynomial time.

Solving is decompaction, not search. Given training pairs, the coordinate is read off: the frame is the one that
carries the input's colour-relabelled grid onto the output's (the canonical frames' quotient), the colour map is
read cell by cell once the frames align, the stack element is read from which layer lands where. The program a
people writes for it is that coordinate's ADDRESS in the people's own chart - the table of shortest words over the
generators (crystals) it holds (a Schreier table of the group they generate). A people that holds no reflection
cannot express a flip, however long it thinks; a people with a richer vocabulary writes shorter addresses.
"""

import hashlib
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

HUES = 10
Grid = Tuple[Tuple[int, ...], ...]                # rows of hues
Volume = Tuple[Grid, ...]                          # layers

# ---------------------------------------------------------------------- op codes (netstratum wire law)
ROT90, ROT180, ROT270, FLIPH, FLIPV, TRANSPOSE, RECOLOR = 1, 2, 3, 4, 5, 6, 7
FLIP_STACK, CYCLE_LAYERS = "flip_stack", "cycle_layers"
HYPER_FLIP, HYPER_CYCLE = "hyper_flip", "hyper_cycle"      # rank 4: the fourth axis (a stack of volumes)
NAMES = {ROT90: "rotate90", ROT180: "rotate180", ROT270: "rotate270", FLIPH: "flip_h", FLIPV: "flip_v",
         TRANSPOSE: "transpose", RECOLOR: "recolor", FLIP_STACK: "flip_stack", CYCLE_LAYERS: "cycle_layers",
         HYPER_FLIP: "hyper_flip", HYPER_CYCLE: "hyper_cycle"}
FRAME_OPS = (ROT90, ROT180, ROT270, FLIPH, FLIPV, TRANSPOSE)
STACK_OPS = (FLIP_STACK, CYCLE_LAYERS)
HYPER_OPS = (HYPER_FLIP, HYPER_CYCLE)


# ---------------------------------------------------------------------- the frame group D4
# An element is (k, m): rotate k quarter turns clockwise, after first mirroring left-right if m. Eight points.
D4 = tuple((k, m) for m in (0, 1) for k in range(4))
IDENTITY = (0, 0)


def frame_of(op: int) -> Tuple[int, int]:
    """Each frame op as a D4 coordinate (FlipV = mirror then a half turn; Transpose = mirror then a quarter turn
    counter-clockwise, i.e. three clockwise)."""
    return {ROT90: (1, 0), ROT180: (2, 0), ROT270: (3, 0), FLIPH: (0, 1), FLIPV: (2, 1), TRANSPOSE: (3, 1)}[op]


def compose(a: Tuple[int, int], b: Tuple[int, int]) -> Tuple[int, int]:
    """Apply a, then b."""
    ka, ma = a
    kb, mb = b
    # mirroring reverses the sense of the rotations already applied
    return ((kb + (-ka if mb else ka)) % 4, ma ^ mb)


def inverse(a: Tuple[int, int]) -> Tuple[int, int]:
    k, m = a
    return (k, 1) if m else ((-k) % 4, 0)


def _rot90(g: Grid) -> Grid:
    rows, cols = len(g), len(g[0])
    return tuple(tuple(g[rows - 1 - c][r] for c in range(rows)) for r in range(cols))


def _mirror(g: Grid) -> Grid:
    return tuple(tuple(reversed(row)) for row in g)


def apply_frame(a: Tuple[int, int], g: Grid) -> Grid:
    k, m = a
    if m:
        g = _mirror(g)
    for _ in range(k):
        g = _rot90(g)
    return g


def recolor(cmap: Sequence[int], g: Grid) -> Grid:
    return tuple(tuple(cmap[h] for h in row) for row in g)


def relabel(g: Grid) -> Tuple[Grid, Tuple[int, ...]]:
    """Colours renamed by first appearance (row-major): the grid's shape, free of what its colours are called."""
    seen: Dict[int, int] = {}
    out = []
    for row in g:
        r = []
        for h in row:
            if h not in seen:
                seen[h] = len(seen)
            r.append(seen[h])
        out.append(tuple(r))
    order = tuple(sorted(seen, key=seen.get))
    return tuple(out), order


# ---------------------------------------------------------------------- canonical frames (crystals)
def canonical(g: Grid) -> Tuple[Grid, Tuple[int, int]]:
    """A grid's crystal: its colour-free form in the canonical orientation (the least of its frame orbit), and the
    frame that carries it there. Eight fixed coordinates of the group act on it - an orbit, not a search."""
    best, best_a = None, IDENTITY
    for a in D4:
        form, _ = relabel(apply_frame(a, g))
        key = (len(form), len(form[0]), form)
        if best is None or key < best:
            best, best_a = key, a
    return best[2], best_a


def stabilizer(g: Grid) -> List[Tuple[int, int]]:
    """The frames that leave a grid's colour-free form unchanged (its own symmetry)."""
    form, _ = relabel(g)
    return [a for a in D4 if relabel(apply_frame(a, g))[0] == form]


# ---------------------------------------------------------------------- reading a coordinate off a pair
def read_pair(i: Grid, o: Grid) -> Optional[List[Tuple[Tuple[int, int], Tuple[int, ...]]]]:
    """Every (frame, colour map) that carries input i onto output o: canonical(o) = canonical(i) fixes the frame
    up to i's own symmetry (the coset frame(i)^-1 . stab . frame(o)), and the colour map is read cell by cell."""
    ci, ai = canonical(i)
    co, ao = canonical(o)
    if ci != co:
        return None                                    # not the same crystal: no frame and recolour relates them
    base = compose(ai, inverse(ao))                    # i -> canonical -> o
    out = []
    for s in stabilizer(i):
        a = compose(s, base)
        moved = apply_frame(a, i)
        cmap = list(range(HUES))
        fixed = {}
        ok = True
        for rm, ro in zip(moved, o):
            for h, t in zip(rm, ro):
                if fixed.setdefault(h, t) != t:
                    ok = False
                    break
            if not ok:
                break
        if ok:
            for h, t in fixed.items():
                cmap[h] = t
            out.append((a, tuple(cmap)))
    return out or None


def read(pairs: Iterable[Tuple[Grid, Grid]]) -> Optional[Tuple[Tuple[int, int], Tuple[int, ...]]]:
    """The coordinate every training pair agrees on (the intersection of their cosets), in normal form: the
    least frame, the colour map with every unconstrained hue fixed. None if no single coordinate fits them all."""
    agreed: Optional[Dict[Tuple[int, int], Dict[int, int]]] = None
    for i, o in pairs:
        cands = read_pair(i, o)
        if not cands:
            return None
        here = {}
        for a, cmap in cands:
            used = {h for row in apply_frame(a, i) for h in row}
            here[a] = {h: cmap[h] for h in used}
        if agreed is None:
            agreed = here
            continue
        merged = {}
        for a, m in agreed.items():
            if a in here:
                both = dict(m)
                if all(both.setdefault(h, t) == t for h, t in here[a].items()):
                    merged[a] = both
        agreed = merged
        if not agreed:
            return None
    if not agreed:
        return None
    a = min(agreed)
    cmap = list(range(HUES))
    for h, t in agreed[a].items():
        cmap[h] = t
    return a, tuple(cmap)


def _orders(n: int):
    """Every element of D_n acting on n positions: (shift, reversed, the order it reads them in)."""
    for rev in (0, 1):
        for shift in range(n):
            order = [((n - 1 - j) if rev else j) for j in range(n)]
            yield shift, rev, (order[-shift:] + order[:-shift] if shift else order)


def read_hyper(pairs):
    """Rank 4 (a stack of volumes): the hyper-stack element read from where each volume lands, and the rank-3
    coordinate every aligned pair of volumes agrees on. None if no single coordinate fits."""
    pairs = list(pairs)
    if not pairs:
        return None
    n = len(pairs[0][0])
    agreed = None
    for xi, xo in pairs:
        if len(xi) != n or len(xo) != n:
            return None
        found = set()
        for shift, rev, order in _orders(n):
            inner = read_stack([(xi[order[j]], xo[j]) for j in range(n)])
            if inner is not None:
                found.add((shift, rev, inner))
        agreed = found if agreed is None else (agreed & found)
        if not agreed:
            return None
    return min(agreed)


def read_stack(pairs: Iterable[Tuple[Volume, Volume]]):
    """Volumes: the layer permutation (a D_L element: (shift, reversed)) and the per-layer coordinate, read from
    where each layer lands. None if no single stack element and planar coordinate fit every pair."""
    pairs = list(pairs)
    if not pairs:
        return None
    L = len(pairs[0][0])
    agreed = None
    for vi, vo in pairs:
        if len(vi) != L or len(vo) != L:
            return None
        found = set()
        for rev in (0, 1):
            for shift in range(L):
                order = [((L - 1 - j) if rev else j) for j in range(L)]
                order = order[-shift:] + order[:-shift] if shift else order
                c = read([(vi[order[j]], vo[j]) for j in range(L)])
                if c is not None:
                    found.add((shift, rev, c))
        agreed = found if agreed is None else (agreed & found)
        if not agreed:
            return None
    return min(agreed)


# ---------------------------------------------------------------------- charts: a people's addresses
def chart(generators: Iterable[int]) -> Dict[Tuple[int, int], List[int]]:
    """The shortest word over the frame generators a people holds for every frame element it can reach - the
    Schreier table of the subgroup they generate (breadth-first over at most eight points; computed once and
    held, a map, not a search for any task)."""
    gens = [g for g in generators if g in FRAME_OPS]
    table: Dict[Tuple[int, int], List[int]] = {IDENTITY: []}
    frontier = [IDENTITY]
    while frontier:
        nxt = []
        for a in frontier:
            for g in gens:
                b = compose(a, frame_of(g))
                if b not in table:
                    table[b] = table[a] + [g]
                    nxt.append(b)
        frontier = nxt
    return table


def stack_chart(generators: Iterable[str], layers: int) -> Dict[Tuple[int, int], List[str]]:
    """Shortest words over the stack generators a people holds for each (shift, reversed) element of D_L."""
    gens = [g for g in generators if g in STACK_OPS]

    def step(a, g):
        shift, rev = a
        if g == CYCLE_LAYERS:
            return ((shift + 1) % layers, rev)
        return ((-shift) % layers, rev ^ 1)            # reversal conjugates the shift
    table = {(0, 0): []}
    frontier = [(0, 0)]
    while frontier:
        nxt = []
        for a in frontier:
            for g in gens:
                b = step(a, g)
                if b not in table:
                    table[b] = table[a] + [g]
                    nxt.append(b)
        frontier = nxt
    return table


def address(coord, frame_gens: Iterable[int], recolors: bool, stack_gens: Iterable[str] = (),
            layers: int = 0) -> Optional[List]:
    """Decompact a coordinate into a program over a people's own crystals, or None if it lies outside what they can
    express. Planar coord: (frame, cmap); volumetric: (shift, reversed, (frame, cmap))."""
    if layers:
        shift, rev, planar = coord
        st = stack_chart(stack_gens, layers).get((shift, rev))
        if st is None:
            return None
        inner = address(planar, frame_gens, recolors)
        return None if inner is None else list(st) + [("per_layer", op) for op in inner]
    frame, cmap = coord
    word = chart(frame_gens).get(frame)
    if word is None:
        return None
    prog: List = list(word)
    if tuple(cmap) != tuple(range(HUES)):
        if not recolors:
            return None
        prog.append((RECOLOR, tuple(cmap)))
    return prog


# ---------------------------------------------------------------------- running a program (the replay path)
def apply_op(op, g):
    if isinstance(op, tuple) and op and op[0] == RECOLOR:
        return recolor(op[1], g)
    return apply_frame(frame_of(op), g)


def run(program: Sequence, x):
    """Apply a program to a grid or (with stack / per-layer ops) a volume."""
    for op in program:
        if op in (FLIP_STACK, HYPER_FLIP):
            x = tuple(reversed(x))
        elif op in (CYCLE_LAYERS, HYPER_CYCLE):
            x = (x[-1],) + tuple(x[:-1])
        elif isinstance(op, tuple) and op and op[0] == "per_volume":
            x = tuple(run([op[1]], v) for v in x)
        elif isinstance(op, tuple) and op and op[0] == "per_layer":
            x = tuple(apply_op(op[1], layer) for layer in x)
        else:
            x = apply_op(op, x)
    return x


def describe(op) -> str:
    if isinstance(op, tuple) and op and op[0] == RECOLOR:
        return "recolor[" + ",".join(str(h) for h in op[1]) + "]"
    if isinstance(op, tuple) and op and op[0] == "per_layer":
        return f"per_layer({describe(op[1])})"
    if isinstance(op, tuple) and op and op[0] == "per_volume":
        return f"per_volume({describe(op[1])})"
    return NAMES[op]


def digest(*parts) -> str:
    h = hashlib.blake2b(digest_size=32)
    for p in parts:
        h.update(repr(p).encode())
    return h.hexdigest()
